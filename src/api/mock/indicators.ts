export const CATALOGUE_BY_KEY = new Map(SEEDS.map((seed, i) => [seed.key, CATALOGUE[i]]))

/** The catalogue detail endpoint accepts any of the three ids. */
export function findIndicator(id: string): CatalogueDetail | undefined {
  return CATALOGUE.find(
    (row) =>
      row.indicator_id === id ||
      row.indicator_detail_id === id ||
      row.published_detail_id === id,
  )
}
