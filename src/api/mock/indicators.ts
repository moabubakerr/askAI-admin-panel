function shiftPeriod(iso: string, granularity: Seed['granularity'], back: number): string {
  const date = new Date(`${iso}T00:00:00Z`)
  const months = granularity === 'Monthly' ? 1 : granularity === 'Quarterly' ? 3 : 12
  date.setUTCMonth(date.getUTCMonth() - back * months)
  return date.toISOString().slice(0, 10)
}

const MONTHS = [
  'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
  'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
]

function label(iso: string, granularity: Seed['granularity']): string {
  const date = new Date(`${iso}T00:00:00Z`)
  const year = date.getUTCFullYear()
  if (granularity === 'Annual') return String(year)
  if (granularity === 'Quarterly') return `Q${Math.floor(date.getUTCMonth() / 3) + 1} ${year}`
  return `${MONTHS[date.getUTCMonth()]} ${year}`
}

function round(value: number, decimals: number): number {
  const factor = 10 ** decimals
  return Math.round(value * factor) / factor
}

function buildSeries(seed: Seed): SeriesPoint[] {
  const points: SeriesPoint[] = []
  // Keep the plotted window readable; the full point count still reports as data_points.
  const shown = Math.min(seed.points, seed.granularity === 'Monthly' ? 24 : 12)
  for (let i = shown - 1; i >= 0; i--) {
    const iso = shiftPeriod(seed.last[1], seed.granularity, i)
    const step = seed.points - 1 - i
    const wobble = Math.sin(step * 1.7) * seed.step * 1.6
    const actual = round(seed.start + seed.step * step + wobble, seed.decimals)
    const target =
      seed.target === null
        ? null
        : round(seed.start + (seed.target - seed.start) * ((step + 1) / (seed.points + 6)), seed.decimals)
    points.push({
      record_id: guid(`${seed.key}-point-${i}`),
      period_label: label(iso, seed.granularity),
      period_date: iso,
      granularity: seed.granularity,
      country_en: 'Qatar',
      actual,
      target,
      // Outlook only on the most recent point, and not for every indicator.
      outlook: i === 0 && seed.target !== null ? round(actual + seed.step * 2, seed.decimals) : null,
    })
  }
  return points
}

